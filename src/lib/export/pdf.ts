/** 等 Svelte 副作用与异步解码稳定下来，切楼层后使用。 */
function waitForRender(): Promise<void> {
	return new Promise((resolve) => {
		// 两帧 rAF 让副作用跑完，再用超时等图片、掩码和房间类型的异步解码。
		requestAnimationFrame(() => requestAnimationFrame(() => setTimeout(resolve, 400)));
	});
}

const BRAND_COLOR: [number, number, number] = [0, 200, 200];
const GRAY: [number, number, number] = [100, 100, 110];
const DARK: [number, number, number] = [30, 30, 40];
const LIGHT_BG: [number, number, number] = [245, 246, 250];
const TABLE_HEADER_BG: [number, number, number] = [35, 40, 55];
const TABLE_ALT_BG: [number, number, number] = [248, 249, 252];

const bandLabels: Record<string, string> = {
	'2.4ghz': '2.4 GHz',
	'5ghz': '5 GHz',
	'6ghz': '6 GHz'
};

const capacityProfileLabels: Record<string, string> = {
	office: 'Office',
	highDensity: 'High density',
	iot: 'IoT / hotel',
	custom: 'Custom'
};

function pct(value: number): string {
	return `${Math.round(value * 100)}%`;
}

function drawHeader(doc: jsPDF, pageWidth: number, margin: number) {
	// 顶部品牌色条
	doc.setFillColor(...BRAND_COLOR);
	doc.rect(0, 0, pageWidth, 3, 'F');

	// 产品名
	doc.setFontSize(11);
	doc.setFont('helvetica', 'bold');
	doc.setTextColor(...BRAND_COLOR);
	doc.text('Aetherax', margin, 12);

	// 副标题
	doc.setFontSize(7);
	doc.setFont('helvetica', 'normal');
	doc.setTextColor(...GRAY);
	doc.text('WiFi Channel Planner', margin + 28, 12);

	// 分隔线
	doc.setDrawColor(220, 220, 230);
	doc.setLineWidth(0.3);
	doc.line(margin, 16, pageWidth - margin, 16);

	doc.setTextColor(...DARK);
}

/**
 * 当前正在写的页码。
 * jsPDF 的类型声明没有暴露 `getCurrentPageInfo()`，所以用窄类型断言调用。
 */
function currentPageNumber(doc: jsPDF): number {
	return (doc as jsPDF & { getCurrentPageInfo(): { pageNumber: number } }).getCurrentPageInfo()
		.pageNumber;
}

function drawFooter(doc: jsPDF, pageWidth: number, pageHeight: number, margin: number) {
	const y = pageHeight - 8;
	doc.setFontSize(6.5);
	doc.setFont('helvetica', 'normal');
	doc.setTextColor(...GRAY);
	// 每页都带工程名，散页打印后仍能对上方案。
	doc.text(`Generated by Aetherax · ${projectMeta.name}`, margin, y);
	doc.text(`Page ${currentPageNumber(doc)}`, pageWidth - margin, y, {
		align: 'right'
	});
	doc.setTextColor(...DARK);
}

/**
 * 等画布真正显示报告要拍的内容。
 * 轮询视图与楼层状态，最多等 3 秒；超时也返回，避免渲染卡住导出。
 */
async function waitForView(
	engine: CanvasEngine,
	single: boolean,
	floorId?: string
): Promise<void> {
	const deadline = performance.now() + 3000;
	for (;;) {
		const tiles = engine.layers.find((layer) => layer.id === 'floor-tiles');
		const viewOk = single ? !tiles?.visible : !!tiles?.visible;
		const floorOk = !floorId || floorState.currentFloorId === floorId;
		if (viewOk && floorOk) return;
		if (performance.now() > deadline) return;
		await new Promise((resolve) => setTimeout(resolve, 50));
	}
}

/**
 * One page that makes the numbers interpretable without reading the manual:
 * what was assumed for capacity and PHY, and what this report is not.
 */
function drawMethodologyPage(
	doc: jsPDF,
	pageWidth: number,
	pageHeight: number,
	margin: number,
	contentWidth: number
): void {
	doc.addPage();
	drawHeader(doc, pageWidth, margin);

	let y = 24;
	doc.setFontSize(15);
	doc.setFont('helvetica', 'bold');
	doc.setTextColor(...DARK);
	doc.text('How this plan was calculated', margin, y);
	y += 7;
	doc.setFontSize(8.5);
	doc.setFont('helvetica', 'normal');
	doc.setTextColor(...GRAY);
	doc.text(
		'Planning assumptions are printed on this page so the coverage and capacity figures can be read in context.',
		margin,
		y
	);
	y += 9;

	const gap = 10;
	const colW = (contentWidth - gap) / 2;
	const leftX = margin;
	const rightX = margin + colW + gap;

	const drawRows = (x: number, startY: number, rows: Array<[string, string]>): number => {
		let rowY = startY;
		for (const [label, value] of rows) {
			doc.setFontSize(7.5);
			doc.setFont('helvetica', 'bold');
			doc.setTextColor(...GRAY);
			doc.text(label, x, rowY);
			doc.setFontSize(8);
			doc.setFont('helvetica', 'normal');
			doc.setTextColor(...DARK);
			const lines = doc.splitTextToSize(value, colW - 34);
			doc.text(lines, x + 34, rowY);
			rowY += Math.max(4.5, lines.length * 3.8) + 2.2;
		}
		return rowY;
	};

	const section = (x: number, title: string, rows: Array<[string, string]>): number => {
		doc.setFontSize(9);
		doc.setFont('helvetica', 'bold');
		doc.setTextColor(...BRAND_COLOR);
		doc.text(title, x, y);
		doc.setTextColor(...DARK);
		return drawRows(x, y + 6, rows);
	};

	const demand = ROOM_DEMAND_MBPS;
	const leftBottom = section(leftX, 'CAPACITY ASSUMPTIONS', [
		['Profile', capacityProfileLabels[projectMeta.capacityProfile] ?? 'Custom'],
		['Activity', `${pct(projectMeta.activityFactor)} of associated devices`],
		[
			'Terminal mix',
			`${pct(projectMeta.oneStreamShare)} 1-stream · ${pct(projectMeta.twoStreamShare)} 2-stream · ${pct(projectMeta.fourStreamShare)} 4-stream (not used)`
		],
		['Demand', `${demand.low} / ${demand.standard} / ${demand.high} Mbps per device`],
		['MAC / utilisation', `${pct(DEFAULT_MAC_EFFICIENCY)} / ${pct(CAPACITY_UTILIZATION)}`],
		['Supply basis', 'median SINR per AP; edge = 5th percentile'],
		['Warning', 'traffic shortfall, required APs, or edge SNR < 20 dB']
	]);

	const rightBottom = section(rightX, 'PHY & PROPAGATION', [
		[
			'PHY tables',
			'802.11ac MCS 0–9; 802.11ax MCS 0–11; GI 800 ns; 2 streams'
		],
		['Path loss', `${projectMeta.pathLossScenario.replace(/-/g, ' ')} · log-distance, 10 m breakpoint`],
		['Walls / floors', 'P.2040 slab transmission; floor material × thickness'],
		['Multipath', 'single/2nd reflection, P.526 knife-edge, directive scattering'],
		['SINR', 'best server; ACIR 25 dB; thermal noise kTB + NF'],
		['Channel', `${bandLabels[apState.band] ?? apState.band} · ${apState.channelWidth} MHz · ${apState.regulatoryDomain.toUpperCase()}`]
	]);

	y = Math.max(leftBottom, rightBottom) + 4;
	const noteLines = doc.splitTextToSize(
		'PLANNING MODEL — NOT SITE ACCEPTANCE. Standard formulas are used for path loss, materials and diffraction, but material thickness, scattering coefficients, ACIR, MAC efficiency, activity and terminal mix remain engineering assumptions. Compare options with this report, then confirm with a site survey. Rate and capacity are not measured throughput.',
		contentWidth - 10
	);
	const noteHeight = noteLines.length * 3.8 + 10;
	doc.setFillColor(...LIGHT_BG);
	doc.roundedRect(margin, y, contentWidth, noteHeight, 1.5, 1.5, 'F');
	doc.setFontSize(7.5);
	doc.setFont('helvetica', 'bold');
	doc.setTextColor(...DARK);
	doc.text('READ THIS BEFORE USING THE NUMBERS', margin + 5, y + 6);
	doc.setFont('helvetica', 'normal');
	doc.setTextColor(...GRAY);
	doc.text(noteLines, margin + 5, y + 11);

	drawFooter(doc, pageWidth, pageHeight, margin);
}

export async function exportPdf(engine: CanvasEngine): Promise<void> {
	const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
	const pageWidth = doc.internal.pageSize.getWidth();
	const pageHeight = doc.internal.pageSize.getHeight();
	const margin = 18;
	const contentWidth = pageWidth - margin * 2;

	const dateStr = new Date().toLocaleDateString('en-US', {
		year: 'numeric',
		month: 'long',
		day: 'numeric'
	});
	const apCount = apState.aps.length;
	const floorCount = floorState.floors.length;
	const sortedFloors = [...floorState.floors].sort((a, b) => a.level - b.level);

	// Traffic is measured per floor; the report shows the building total, not a
	// single floor's figure dressed up as the whole project.
	let hasTraffic = false;
	let trafficDemandMbps = 0;
	let trafficSupplyMbps = 0;
	let trafficRequiredAps = 0;
	let trafficActualAps = 0;
	for (const fc of floorCoverage.values()) {
		if (!fc.traffic) continue;
		hasTraffic = true;
		trafficDemandMbps += fc.traffic.demandMbps;
		trafficSupplyMbps += fc.traffic.supplyMbps;
		trafficRequiredAps += fc.traffic.requiredAps;
		trafficActualAps += fc.traffic.apCount;
	}

	// 先算出每层的覆盖率
	const originalFloorId = floorState.currentFloorId;
	// 每张布局图都是画布截图，取景按报告需要而不是用户当前的缩放平移；每次截图前先 fit，
	// 结束时把相机恢复原样。
	const cameraBefore = engine.camera.getState();
	for (const floor of sortedFloors) {
		if (!floorCoverage.has(floor.id)) {
			switchFloor(floor.id);
			engine.markDirty();
			await waitForRender();
			await updateCoverage();
		}
	}
	// 拍封面之前切回原来的楼层
	if (floorState.currentFloorId !== originalFloorId) {
		switchFloor(originalFloorId);
		engine.markDirty();
		await waitForRender();
	}

	// ─── 封面 ─────────────────────────────────────────────────────────

	drawHeader(doc, pageWidth, margin);

	let y = 50;
	doc.setFontSize(28);
	doc.setFont('helvetica', 'bold');
	doc.setTextColor(...DARK);
	doc.text(projectMeta.name, margin, y);

	y += 12;
	doc.setFontSize(11);
	doc.setFont('helvetica', 'normal');
	doc.setTextColor(...GRAY);
	doc.text(dateStr, margin, y);

	y += 14;
	doc.setFontSize(10);
	doc.setTextColor(...DARK);

	const stats: string[] = [
		`${apCount} access point${apCount !== 1 ? 's' : ''}`,
		`${floorCount} floor${floorCount !== 1 ? 's' : ''}`
	];
	if (solverState.lastResult) {
		stats.push(
			`${solverState.lastResult.colorCount} channel${solverState.lastResult.colorCount !== 1 ? 's' : ''} used`
		);
		if (solverState.lastResult.conflicts.length > 0) {
			stats.push(
				`${solverState.lastResult.conflicts.length} conflict${solverState.lastResult.conflicts.length !== 1 ? 's' : ''}`
			);
		}
	}
	const buildingCov = getBuildingCoverage();
	if (buildingCov > 0) {
		stats.push(`${buildingCov}% building coverage`);
	}
	if (hasTraffic) {
		stats.push(
			`Traffic demand / capacity: ${trafficDemandMbps} / ${trafficSupplyMbps} Mbps`
		);
		if (trafficRequiredAps > trafficActualAps) {
			stats.push(`Traffic needs ${trafficRequiredAps} APs; ${trafficActualAps} placed`);
		}
	}
	// 跑过优化后同时列出同频干扰与争用空口时间，两者含义不同。
	if (optimizerState.interferenceMeasured) {
		stats.push(`Co-channel interference ${optimizerState.interference}%`);
		stats.push(`Contended airtime (CCA) ${optimizerState.contention}%`);
	}

	for (const stat of stats) {
		doc.text(`•  ${stat}`, margin + 2, y);
		y += 6;
	}

	// 逐层覆盖率
	if (floorCoverage.size > 0 && floorCount > 1) {
		y += 4;
		doc.setFontSize(9);
		doc.setFont('helvetica', 'bold');
		doc.text('Coverage by floor', margin, y);
		y += 6;
		doc.setFont('helvetica', 'normal');
		for (const floor of sortedFloors) {
			const fc = floorCoverage.get(floor.id);
			if (fc) {
				doc.text(`${floor.name}: ${fc.coverage}%`, margin + 4, y);
				y += 5;
			}
		}
	}

	/*
	 * 本次方案的计算参数：频段、信道宽度、路径损耗场景、客户端高度等。
	 * 放在标题下方，避免长工程名与右列重叠。
	 */
	{
		y += 8;
		doc.setFontSize(9);
		doc.setFont('helvetica', 'bold');
		doc.setTextColor(...GRAY);
		doc.text('PLAN PARAMETERS', margin, y);
		y += 6;

		const params: Array<[string, string]> = [
			['Band', bandLabels[apState.band] ?? String(apState.band)],
			['Channel width', `${apState.channelWidth} MHz`],
			['Regulatory domain', apState.regulatoryDomain.toUpperCase()],
			['Client height', `${projectMeta.clientHeight.toFixed(1)} m`],
			['Path loss', projectMeta.pathLossScenario.replace(/-/g, ' ')],
			['PHY', '802.11ac / 802.11ax · 2 streams'],
			['Capacity', `${capacityProfileLabels[projectMeta.capacityProfile] ?? 'Custom'} · ${pct(projectMeta.activityFactor)} active`],
			['Units', floorplanState.unitSystem === 'imperial' ? 'Imperial (ft)' : 'Metric (m)']
		];
		// 两列三行排布，避免占满封面。
		doc.setFontSize(8.5);
		for (let i = 0; i < params.length; i++) {
			const [label, value] = params[i]!;
			const colX = margin + (i % 2 === 0 ? 2 : contentWidth / 2);
			const rowY = y + Math.floor(i / 2) * 5.5;
			doc.setFont('helvetica', 'normal');
			doc.setTextColor(...GRAY);
			doc.text(label, colX, rowY);
			doc.setTextColor(...DARK);
			doc.text(value, colX + 34, rowY);
		}
		y += Math.ceil(params.length / 2) * 5.5;
	}

	drawFooter(doc, pageWidth, pageHeight, margin);

	drawMethodologyPage(doc, pageWidth, pageHeight, margin, contentWidth);

	// ─── 各层布局页（图片尺寸统一） ───────────────────────

	// 固定图片区域：每页起始 Y 与最大高度一致。
	const layoutImgY = 28;
	const layoutMaxH = pageHeight - layoutImgY - margin - 5;

	// 多层视图是整栋楼一张图：先单独拍一张总览，再把楼层页切回单层视图，保证每页只显示本层。
	const originalView = appState.floorView;
	if (originalView !== 'single') {
		if (fitCanvasToContent(engine, true)) await waitForRender();
		const stacked = captureCanvas(engine);
		const aspect = stacked.width / stacked.height;
		let imgWidth = contentWidth;
		let imgHeight = imgWidth / aspect;
		if (imgHeight > layoutMaxH) {
			imgHeight = layoutMaxH;
			imgWidth = imgHeight * aspect;
		}
		doc.addPage();
		drawHeader(doc, pageWidth, margin);
		doc.setFontSize(14);
		doc.setFont('helvetica', 'bold');
		doc.setTextColor(...DARK);
		doc.text('Building overview', margin, 24);
		doc.addImage(
			stacked.data,
			'JPEG',
			margin + (contentWidth - imgWidth) / 2,
			layoutImgY,
			imgWidth,
			imgHeight
		);
		drawFooter(doc, pageWidth, pageHeight, margin);

		appState.floorView = 'single';
		engine.markDirty();
		await waitForRender();
	}

	for (const floor of sortedFloors) {
		if (floor.id !== floorState.currentFloorId) {
			switchFloor(floor.id);
			engine.markDirty();
			await waitForRender();
		}
		// 等画布确认只显示本层后再截图。
		await waitForView(engine, true, floor.id);

		doc.addPage();
		drawHeader(doc, pageWidth, margin);

		// 楼层名与覆盖率
		y = 24;
		doc.setFontSize(12);
		doc.setFont('helvetica', 'bold');
		doc.setTextColor(...DARK);
		doc.text(floor.name, margin, y);

		const fc = floorCoverage.get(floor.id);
		if (fc) {
			doc.setFontSize(9);
			doc.setFont('helvetica', 'normal');
			doc.setTextColor(...GRAY);
			doc.text(`Coverage: ${fc.coverage}%`, pageWidth - margin, y, { align: 'right' });
		}
		doc.setTextColor(...DARK);

		// 按统一尺寸截图
		if (fitCanvasToContent(engine, true)) await waitForRender();
		const canvasImg = captureCanvas(engine);
		const aspectRatio = canvasImg.width / canvasImg.height;
		let imgWidth = contentWidth;
		let imgHeight = imgWidth / aspectRatio;
		if (imgHeight > layoutMaxH) {
			imgHeight = layoutMaxH;
			imgWidth = imgHeight * aspectRatio;
		}
		const imgX = margin + (contentWidth - imgWidth) / 2;
		doc.addImage(canvasImg.data, 'JPEG', imgX, layoutImgY, imgWidth, imgHeight);

		drawFooter(doc, pageWidth, pageHeight, margin);
	}

	// 恢复原来的楼层
	if (floorState.currentFloorId !== originalFloorId) {
		switchFloor(originalFloorId);
		engine.markDirty();
		await waitForRender();
	}
	// 恢复用户原来的视图模式
	if (originalView !== 'single') {
		appState.floorView = originalView;
		engine.markDirty();
		await waitForRender();
	}
	// 把相机恢复成导出前的状态。
	engine.camera.setState(cameraBefore);
	engine.markDirty();
	await waitForRender();

	// ─── 从第 2 页起：AP 清单 ─────────────────────────────

	doc.addPage();
	drawHeader(doc, pageWidth, margin);

	y = 24;
	doc.setFontSize(14);
	doc.setFont('helvetica', 'bold');
	doc.text('Access Point Schedule', margin, y);

	y += 10;

	// 表格列定义
	const hasModel = apState.aps.some((ap) => ap.modelLabel);

	type Col = {
		header: string;
		width: number;
		getValue: (ap: (typeof apState.aps)[0]) => string;
	};
	const cols: Col[] = [
		{ header: 'NAME', width: 30, getValue: (ap) => ap.name },
		{ header: 'MODEL', width: hasModel ? 40 : 30, getValue: (ap) => ap.modelLabel ?? 'Custom' },
		{ header: 'BAND', width: 20, getValue: (ap) => bandLabels[ap.band] ?? ap.band },
		{ header: 'WIDTH', width: 20, getValue: (ap) => `${ap.channelWidth} MHz` },
		{
			header: 'CHANNEL',
			width: 18,
			getValue: (ap) => (ap.assignedChannel !== null ? String(ap.assignedChannel) : '—')
		},
		{ header: 'POWER', width: 18, getValue: (ap) => `${ap.power} dBm` },
		/*
		 * 安装方式、安装高度与朝向；朝向只对壁挂设备有意义。
		 */
		{ header: 'MOUNT', width: 22, getValue: (ap) => ap.mount },
		{ header: 'HEIGHT', width: 20, getValue: (ap) => `${ap.mountHeightM.toFixed(1)} m` },
		{
			header: 'FACING',
			width: 20,
			getValue: (ap) => (ap.mount === 'wall' ? `${Math.round(ap.facingDeg)}°` : '—')
		}
	];

	for (const floor of sortedFloors) {
		const floorAps = apState.aps.filter((ap) => ap.floorId === floor.id);
		if (floorAps.length === 0 && floorCount > 1) continue;
		const apsToShow = floorCount === 1 ? apState.aps : floorAps;

		// 楼层分组标题
		if (floorCount > 1) {
			if (y > pageHeight - 30) {
				doc.addPage();
				drawHeader(doc, pageWidth, margin);
				y = 24;
			}
			doc.setFillColor(...LIGHT_BG);
			doc.roundedRect(margin, y - 4, contentWidth, 8, 1, 1, 'F');
			doc.setFontSize(9);
			doc.setFont('helvetica', 'bold');
			doc.setTextColor(...DARK);
			doc.text(floor.name, margin + 3, y + 1);

			// 有覆盖率就一并显示
			const fc = floorCoverage.get(floor.id);
			if (fc) {
				doc.setFont('helvetica', 'normal');
				doc.setTextColor(...GRAY);
				doc.text(`Coverage: ${fc.coverage}%`, margin + contentWidth - 3, y + 1, {
					align: 'right'
				});
			}
			/*
			 * 本层结构：吊顶高度、楼板厚度、材质与 AP 数量。
			 */
			const material = FLOOR_MATERIALS.find((m) => m.id === floor.floorMaterial);
			doc.setFont('helvetica', 'normal');
			doc.setFontSize(7);
			doc.setTextColor(...GRAY);
			const trafficText = fc?.traffic
				? `  ·  traffic ${fc.traffic.demandMbps}/${fc.traffic.supplyMbps} Mbps`
				: '';
			doc.text(
				[
					`ceiling ${floor.ceilingHeight.toFixed(1)} m`,
					`slab ${floor.floorThickness.toFixed(2)} m`,
					material ? material.name : 'unknown material',
					`${floorAps.length} access point${floorAps.length === 1 ? '' : 's'}`
				].join('  ·  ') + trafficText,
				margin + 3,
				y + 6
			);
			doc.setTextColor(...DARK);
			y += 10;
		}

		// 表头
		doc.setFillColor(...TABLE_HEADER_BG);
		doc.rect(margin, y - 4, contentWidth, 7, 'F');
		doc.setFontSize(6.5);
		doc.setFont('helvetica', 'bold');
		doc.setTextColor(255, 255, 255);

		let x = margin + 2;
		for (const col of cols) {
			doc.text(col.header, x, y);
			x += col.width;
		}
		doc.setTextColor(...DARK);
		y += 8;

		// 表格行
		doc.setFontSize(8);
		doc.setFont('helvetica', 'normal');

		for (let idx = 0; idx < apsToShow.length; idx++) {
			if (y > pageHeight - 15) {
				drawFooter(doc, pageWidth, pageHeight, margin);
				doc.addPage();
				drawHeader(doc, pageWidth, margin);
				y = 24;
			}

			const ap = apsToShow[idx]!;
			if (idx % 2 === 0) {
				doc.setFillColor(...TABLE_ALT_BG);
				doc.rect(margin, y - 4, contentWidth, 7, 'F');
			}

			x = margin + 2;
			for (const col of cols) {
				doc.text(col.getValue(ap), x, y);
				x += col.width;
			}
			y += 7;
		}

		y += 4;
	}

	// ─── 汇总 ────────────────────────────────────────────────────────

	if (y > pageHeight - 35) {
		drawFooter(doc, pageWidth, pageHeight, margin);
		doc.addPage();
		drawHeader(doc, pageWidth, margin);
		y = 24;
	}

	y += 4;
	doc.setDrawColor(220, 220, 230);
	doc.line(margin, y, margin + contentWidth, y);
	y += 8;

	doc.setFontSize(10);
	doc.setFont('helvetica', 'bold');
	doc.text('Summary', margin, y);
	y += 7;

	doc.setFontSize(8.5);
	doc.setFont('helvetica', 'normal');

	const summaryItems: string[] = [];
	summaryItems.push(
		`${apCount} access point${apCount !== 1 ? 's' : ''} across ${floorCount} floor${floorCount !== 1 ? 's' : ''}`
	);

	if (solverState.lastResult) {
		summaryItems.push(
			`${solverState.lastResult.colorCount} channel${solverState.lastResult.colorCount !== 1 ? 's' : ''} used, ${solverState.lastResult.conflicts.length} conflict${solverState.lastResult.conflicts.length !== 1 ? 's' : ''}`
		);
	}

	if (floorCoverage.size > 0) {
		for (const floor of sortedFloors) {
			const fc = floorCoverage.get(floor.id);
			if (fc) {
				summaryItems.push(`${floor.name} coverage: ${fc.coverage}%`);
			}
		}
		if (floorCount > 1 && floorCoverage.size > 1) {
			summaryItems.push(`Building average coverage: ${getBuildingCoverage()}%`);
		}
	}

	if (hasTraffic) {
		summaryItems.push(
			`Traffic demand / capacity: ${trafficDemandMbps} / ${trafficSupplyMbps} Mbps`
		);
		summaryItems.push(
			`Traffic-required APs: ${trafficRequiredAps}; placed: ${trafficActualAps}`
		);
	}

	for (const item of summaryItems) {
		doc.text(`•  ${item}`, margin + 2, y);
		y += 5;
	}

	drawFooter(doc, pageWidth, pageHeight, margin);

	// 保存文件
	const filename = projectMeta.name.replace(/[^a-zA-Z0-9-_]/g, '_');
	doc.save(`${filename}-report.pdf`);
}

/** 把当前画布截成 JPEG data URL，按 2 倍分辨率。 */
function captureCanvas(engine: CanvasEngine): { data: string; width: number; height: number } {
	const canvasEl = engine.canvas;
	const scale = 2;
	const srcWidth = canvasEl.width / (window.devicePixelRatio || 1);
	const srcHeight = canvasEl.height / (window.devicePixelRatio || 1);
	const tempCanvas = document.createElement('canvas');
	tempCanvas.width = srcWidth * scale;
	tempCanvas.height = srcHeight * scale;
	const ctx = tempCanvas.getContext('2d')!;

	// 走引擎自己的绘制循环，只画 exportable 不为 false 的图层。
	engine.drawInto(
		{ ctx, width: srcWidth, height: srcHeight, dpr: scale, background: RENDER_BACKGROUND },
		{ include: (layer) => layer.exportable !== false }
	);

	return {
		data: tempCanvas.toDataURL('image/jpeg', 0.9),
		width: srcWidth,
		height: srcHeight
	};
}
